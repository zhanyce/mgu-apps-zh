#!/usr/bin/env node
/*
 * cockpit_fullview.js — MGU Store companion tool hook (Node 8.16.2 / ES2017).
 *
 * Keeps waze-on-cluster's 1632x720 FullView H.264 CarPlay/AMAP/Baidu map
 * projection, contour mask, overspeed rim, and HUD map intact while disabling
 * its 3 built-in C++ pods (speed_pod, guidance_pod, trip_pod) so they never
 * overlap Cockpit+'s high-precision overlays on the cluster.
 */
'use strict';

var fs = require('fs');
var path = require('path');
var childProcess = require('child_process');

var PROFILE_NAME = 'ID7-cockpit';
var STATE_FILE = 'cockpit-fullview.state.json';
var CR_STATE_FILE = 'cockpit-fullview.cr-state.json';
var BACKUP_SUFFIX = '.cockpit-bak';
var POD_KEYS = ['speed_pod', 'guidance_pod', 'trip_pod'];

var FALLBACK_ID7_PROFILE = [
  '# Fallback ID7 FullView profile generated by cockpit-fullview',
  'fullview_mode = panel-safe',
  'panel_pos = 144,0',
  'shape_bottom = 408x168',
  'shape_top = 374x354',
  'hud_rect = 113,128,284x88',
  '',
  '[waze-on-cluster]',
  'speed_pod = 0',
  'guidance_pod = 0',
  'trip_pod = 0',
  'alert = 1',
  'units = km/h',
  ''
].join('\n');

function mkdirp(dirPath) {
  if (!dirPath || fs.existsSync(dirPath)) return;
  var parent = path.dirname(dirPath);
  if (parent && parent !== dirPath) mkdirp(parent);
  try {
    fs.mkdirSync(dirPath);
  } catch (err) {
    if (err.code !== 'EEXIST') throw err;
  }
}

function safeUnlink(filePath) {
  try {
    if (fs.existsSync(filePath)) fs.unlinkSync(filePath);
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
}

function findSourceId7Profile(wocDir) {
  var candidates = [
    path.join(wocDir, 'vehicles', 'ID7.conf'),
    path.join(wocDir, 'current', 'vehicles', 'ID7.conf')
  ];
  var versionsDir = path.join(wocDir, 'versions');
  if (fs.existsSync(versionsDir)) {
    try {
      var vers = fs.readdirSync(versionsDir).sort().reverse();
      for (var i = 0; i < vers.length; i++) {
        candidates.push(path.join(versionsDir, vers[i], 'vehicles', 'ID7.conf'));
      }
    } catch (err) {
      // ignore unreadable versions directory
    }
  }
  for (var j = 0; j < candidates.length; j++) {
    if (fs.existsSync(candidates[j])) {
      return {
        path: candidates[j],
        text: fs.readFileSync(candidates[j], 'utf8')
      };
    }
  }
  return null;
}

function upsertIniKey(text, key, value, sectionName) {
  var eol = text.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  var lines = text.split(/\r?\n/);
  var keyRe = new RegExp('^\\s*' + key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*=');
  var secRe = sectionName
    ? new RegExp('^\\s*\\[' + sectionName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\]\\s*$', 'i')
    : null;
  var anySecRe = /^\s*\[[^\]]+\]\s*$/;

  var inTargetSection = !sectionName;
  var targetSecStart = -1;
  var targetSecEnd = -1;
  var replaced = false;

  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    if (secRe && secRe.test(line)) {
      inTargetSection = true;
      targetSecStart = i;
      targetSecEnd = i + 1;
      continue;
    }
    if (anySecRe.test(line)) {
      if (inTargetSection && targetSecEnd >= 0) targetSecEnd = i;
      inTargetSection = !sectionName;
      continue;
    }
    if (inTargetSection && targetSecStart >= 0) {
      targetSecEnd = i + 1;
    }
    if (inTargetSection && keyRe.test(line)) {
      lines[i] = key + ' = ' + value;
      replaced = true;
    }
  }

  if (!replaced) {
    if (!sectionName) {
      // Top-level ini key before first [section] or appended if none
      var firstSec = -1;
      for (var k = 0; k < lines.length; k++) {
        if (anySecRe.test(lines[k])) {
          firstSec = k;
          break;
        }
      }
      if (firstSec >= 0) {
        lines.splice(firstSec, 0, key + ' = ' + value);
      } else {
        while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
        lines.push(key + ' = ' + value, '');
      }
    } else if (targetSecStart >= 0) {
      lines.splice(targetSecEnd, 0, key + ' = ' + value);
    } else {
      while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
      if (lines.length > 0) lines.push('');
      lines.push('[' + sectionName + ']', key + ' = ' + value, '');
    }
  }

  var out = lines.join(eol);
  if (out.slice(-eol.length) !== eol) out += eol;
  return out;
}

function buildCockpitProfileText(srcText) {
  var banner = '# Generated by cockpit-fullview for Cockpit+ (pure 1632x720 FullView map, zero C++ pod overlap)\n';
  var body = srcText.replace(/^\uFEFF/, '');
  var section = /^\s*\[waze-on-cluster\]\s*$/im.test(body) ? 'waze-on-cluster' : null;
  for (var i = 0; i < POD_KEYS.length; i++) {
    body = upsertIniKey(body, POD_KEYS[i], '0', section);
  }
  return banner + body;
}

function stripManagedKeys(text) {
  var eol = text.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  var lines = text.split(/\r?\n/);
  var filtered = [];
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    if (/^\s*#\s*Managed by cockpit-fullview\b/.test(line)) continue;
    if (/^\s*(fullview_profile|speed_pod|guidance_pod|trip_pod)\s*=/.test(line)) continue;
    filtered.push(line);
  }
  return filtered.join(eol);
}

function tryRestartService(unitName, opts) {
  var skip = opts && opts.skipSystemctl;
  var mockLog = opts && opts.mockLog;
  if (mockLog) {
    fs.appendFileSync(mockLog, 'systemctl try-restart ' + unitName + '\n', 'utf8');
  }
  if (skip) return;
  try {
    childProcess.execFileSync('systemctl', ['try-restart', unitName], {
      stdio: 'ignore',
      timeout: 8000
    });
  } catch (err) {
    // Non-fatal: service may be idle/unloaded while parked or inactive
  }
}

function tryRestartWazeService(opts) {
  tryRestartService('waze-on-cluster.service', opts);
}

function repairClusterRenderConf(crDir, opts) {
  if (!crDir || !fs.existsSync(crDir)) return { changed: false, reason: 'cluster-render dir absent' };
  var localConfPath = path.join(crDir, 'cluster-render.local.conf');
  if (!fs.existsSync(localConfPath)) return { changed: false, reason: 'no cluster-render.local.conf' };

  var origText = fs.readFileSync(localConfPath, 'utf8');
  var hasConflictScene = /^\s*panel_scene_id\s*=\s*0x0*10004f0\b/im.test(origText);
  var hasConflictSlot = /^\s*panel_slot\s*=\s*0x0*20[12]\b/im.test(origText);
  if (!hasConflictScene && !hasConflictSlot) {
    return { changed: false, reason: 'cluster-render.local.conf clean' };
  }

  var backupPath = localConfPath + BACKUP_SUFFIX;
  var crStatePath = path.join(crDir, CR_STATE_FILE);
  if (!fs.existsSync(backupPath)) {
    fs.writeFileSync(backupPath, origText, 'utf8');
  }
  if (!fs.existsSync(crStatePath)) {
    fs.writeFileSync(crStatePath, JSON.stringify({
      repairedSceneId: hasConflictScene,
      repairedSlot: hasConflictSlot
    }, null, 2) + '\n', 'utf8');
  }

  var nextText = origText;
  if (hasConflictScene) {
    nextText = upsertIniKey(nextText, 'panel_scene_id', '0x010004f8', null);
  }
  if (hasConflictSlot) {
    nextText = upsertIniKey(nextText, 'panel_slot', '0x203', null);
  }
  fs.writeFileSync(localConfPath, nextText, 'utf8');
  tryRestartService('cluster-render.service', opts);
  return { changed: true, repairedSceneId: hasConflictScene, repairedSlot: hasConflictSlot };
}

function restoreClusterRenderConf(crDir, opts) {
  if (!crDir || !fs.existsSync(crDir)) return { restored: false };
  var localConfPath = path.join(crDir, 'cluster-render.local.conf');
  var backupPath = localConfPath + BACKUP_SUFFIX;
  var crStatePath = path.join(crDir, CR_STATE_FILE);
  if (!fs.existsSync(backupPath)) {
    safeUnlink(crStatePath);
    return { restored: false };
  }
  fs.writeFileSync(localConfPath, fs.readFileSync(backupPath, 'utf8'), 'utf8');
  safeUnlink(backupPath);
  safeUnlink(crStatePath);
  tryRestartService('cluster-render.service', opts);
  return { restored: true };
}

function activate(opts) {
  var wocDir = (opts && opts.wocDir) || process.env.COCKPIT_WOC_DIR || '/var/opt/waze-on-cluster';
  var crDir = (opts && opts.crDir) || process.env.COCKPIT_CR_DIR || '/var/opt/cluster-render';
  var skipSystemctl = (opts && opts.skipSystemctl) || process.env.COCKPIT_SKIP_SYSTEMCTL === '1';
  var mockLog = (opts && opts.mockLog) || process.env.COCKPIT_MOCK_LOG || '';

  // Repair stale panel_scene_id = 0x010004f0 or panel_slot = 0x202 left over from legacy 2.x installs
  var crRes = repairClusterRenderConf(crDir, { skipSystemctl: skipSystemctl, mockLog: mockLog });
  var crNote = crRes.changed ? ' (repaired stale cluster-render.local.conf)' : '';

  if (!fs.existsSync(wocDir)) {
    return {
      status: 'waze-on-cluster not installed; skipped FullView pod configuration' + crNote
    };
  }

  var src = findSourceId7Profile(wocDir);
  if (!src) {
    return {
      status: 'Open-source waze-on-cluster active (no C++ pods to override)' + crNote
    };
  }
  var vehiclesDir = path.join(wocDir, 'vehicles');
  mkdirp(vehiclesDir);

  var profilePath = path.join(vehiclesDir, PROFILE_NAME + '.conf');
  fs.writeFileSync(profilePath, buildCockpitProfileText(src.text), 'utf8');

  var localConfPath = path.join(wocDir, 'waze-on-cluster.local.conf');
  var backupPath = localConfPath + BACKUP_SUFFIX;
  var statePath = path.join(wocDir, STATE_FILE);

  var hadLocalConf = fs.existsSync(localConfPath);
  if (!fs.existsSync(statePath)) {
    fs.writeFileSync(statePath, JSON.stringify({
      hadLocalConf: hadLocalConf,
      profilePath: profilePath,
      sourceProfile: src.path
    }, null, 2) + '\n', 'utf8');
  }
  if (hadLocalConf && !fs.existsSync(backupPath)) {
    fs.writeFileSync(backupPath, fs.readFileSync(localConfPath, 'utf8'), 'utf8');
  }

  var localText = hadLocalConf
    ? fs.readFileSync(localConfPath, 'utf8')
    : '# Managed by cockpit-fullview: keep FullView map and disable overlapping C++ pods\n';
  localText = upsertIniKey(localText, 'fullview_profile', PROFILE_NAME, null);
  var localSec = /^\s*\[waze-on-cluster\]\s*$/im.test(localText) ? 'waze-on-cluster' : null;
  for (var i = 0; i < POD_KEYS.length; i++) {
    localText = upsertIniKey(localText, POD_KEYS[i], '0', localSec);
  }
  fs.writeFileSync(localConfPath, localText, 'utf8');

  tryRestartWazeService({ skipSystemctl: skipSystemctl, mockLog: mockLog });

  return {
    status: 'Configured waze-on-cluster (' + PROFILE_NAME + ') for pure FullView + Cockpit+' + crNote
  };
}

function deactivate(opts) {
  var wocDir = (opts && opts.wocDir) || process.env.COCKPIT_WOC_DIR || '/var/opt/waze-on-cluster';
  var crDir = (opts && opts.crDir) || process.env.COCKPIT_CR_DIR || '/var/opt/cluster-render';
  var skipSystemctl = (opts && opts.skipSystemctl) || process.env.COCKPIT_SKIP_SYSTEMCTL === '1';
  var mockLog = (opts && opts.mockLog) || process.env.COCKPIT_MOCK_LOG || '';

  var crRes = restoreClusterRenderConf(crDir, { skipSystemctl: skipSystemctl, mockLog: mockLog });

  if (!fs.existsSync(wocDir)) {
    return {
      status: crRes.restored
        ? 'Restored cluster-render.local.conf (waze-on-cluster not present)'
        : 'waze-on-cluster not present; nothing to restore'
    };
  }

  var localConfPath = path.join(wocDir, 'waze-on-cluster.local.conf');
  var backupPath = localConfPath + BACKUP_SUFFIX;
  var statePath = path.join(wocDir, STATE_FILE);
  var profilePath = path.join(wocDir, 'vehicles', PROFILE_NAME + '.conf');

  var state = null;
  if (fs.existsSync(statePath)) {
    try {
      state = JSON.parse(fs.readFileSync(statePath, 'utf8'));
    } catch (err) {
      state = null;
    }
  }

  var wocChanged = false;
  if (fs.existsSync(backupPath)) {
    fs.writeFileSync(localConfPath, fs.readFileSync(backupPath, 'utf8'), 'utf8');
    safeUnlink(backupPath);
    wocChanged = true;
  } else if (state && state.hadLocalConf === false) {
    safeUnlink(localConfPath);
    wocChanged = true;
  } else if (fs.existsSync(localConfPath) && fs.existsSync(statePath)) {
    var cleaned = stripManagedKeys(fs.readFileSync(localConfPath, 'utf8')).trim();
    if (!cleaned) safeUnlink(localConfPath);
    else fs.writeFileSync(localConfPath, cleaned + '\n', 'utf8');
    wocChanged = true;
  }

  if (fs.existsSync(profilePath)) {
    safeUnlink(profilePath);
    wocChanged = true;
  }
  safeUnlink(statePath);

  if (wocChanged) {
    tryRestartWazeService({ skipSystemctl: skipSystemctl, mockLog: mockLog });
  }

  return {
    status: crRes.restored
      ? 'Restored original waze-on-cluster & cluster-render configs'
      : 'Restored original waze-on-cluster profile'
  };
}

function main() {
  var cmd = process.argv[2] || 'activate';
  var res;
  if (cmd === 'activate') res = activate();
  else if (cmd === 'deactivate') res = deactivate();
  else throw new Error('Unknown command: ' + cmd);
  process.stdout.write(JSON.stringify(res) + '\n');
}

if (require.main === module) {
  try {
    main();
  } catch (err) {
    process.stderr.write((err && err.stack ? err.stack : String(err)) + '\n');
    process.exit(1);
  }
}

module.exports = {
  PROFILE_NAME: PROFILE_NAME,
  findSourceId7Profile: findSourceId7Profile,
  upsertIniKey: upsertIniKey,
  buildCockpitProfileText: buildCockpitProfileText,
  repairClusterRenderConf: repairClusterRenderConf,
  restoreClusterRenderConf: restoreClusterRenderConf,
  activate: activate,
  deactivate: deactivate
};
